def compute_stamp() -> str:
    """Content hash of every input CMake needs to decide whether to regenerate.

    Content, not mtimes: cross-platform-actions rsyncs the workspace into the
    BSD VMs and timestamps do not survive that reliably.
    """
    h = hashlib.sha256()
    h.update(f"schema={SCHEMA}\n".encode())
    for p in (TOML, Path(__file__), REPO / "thirdparty" / "raylib" / "src" / "config.h"):
        h.update(p.read_bytes() if p.exists() else b"<missing>")
    # The version lands inside generated.properties and project.yml.
    h.update("|".join(map(str, resolve_version())).encode())
    return h.hexdigest()


