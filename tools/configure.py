class ConfigError(Exception):
    """A problem the user must fix in their config, reported without a traceback.

    `where` is an optional ("section.subsection", "key") pair naming what the
    error is about, so the reporter can point at the line. It is almost never
    passed: nearly every message in this file already opens with `[section] key`
    and locate() reads it back out of the message itself. Pass it only when the
    message cannot follow that shape.
    """

    def __init__(self, message: str, where: tuple[str, str | None] | None = None):
        super().__init__(message)
        self.where = where


# `[section]`, or `[section.sub]`, optionally followed by the key. This is the
# shape every rejection in this file is written in, which is what lets the
# location come for free instead of being threaded through sixty call sites.
_WHERE_RE = re.compile(r"^\[([a-z0-9_.]+)\]:?\s+([a-z0-9_]+)?")


def locate(section: str, key: str | None) -> tuple[int, str] | None:
    """The 1-based line of `key` inside `[section]` in the .toml, and its text.

    A hand-rolled scan rather than a TOML library, because tomllib throws the
    positions away and the only thing that matters here is pointing a human at
    the right line. Falls back to the section header when the key is absent —
    which is the honest answer for a value the user never wrote and is getting
    from DEFAULTS.
    """
    if not TOML.exists():
        return None
    try:
        lines = TOML.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None

    here = None
    header_at = None
    for i, raw in enumerate(lines, start=1):
        line = raw.strip()
        if line.startswith("[") and "]" in line:
            here = line[1:line.index("]")].strip()
            if here == section:
                header_at = (i, raw)
            continue
        if here != section or key is None or not line or line.startswith("#"):
            continue
        # `key = value`, with the name on its own before the equals sign.
        name, sep, _ = line.partition("=")
        if sep and name.strip() == key:
            return (i, raw)
    return header_at


def locate_from(exc: ConfigError) -> tuple[int, str] | None:
    """Where an error happened, from its `where` or from its own message."""
    if exc.where is not None:
        return locate(exc.where[0], exc.where[1])
    match = _WHERE_RE.match(str(exc))
    if match is None:
        return None
    return locate(match.group(1), match.group(2))


def report(exc: ConfigError) -> None:
    """Print an error the way somebody can act on it: where, what, and what to do.

    The rule this serves is in CLAUDE.md — a bad config fails HERE, in second
    one, and never at `cmake --preset` or twenty minutes into a runner. Getting
    the line right is most of what makes that true in practice, because
    "[android] min_sdk must be between 21 and 36" is a different experience
    depending on whether you have to go and find it.
    """
    print("", file=sys.stderr)
    spot = locate_from(exc)
    if spot is not None:
        number, text = spot
        gutter = f"  {TOML.name}:{number}:"
        print(f"{gutter} {text.strip()}", file=sys.stderr)
        print(f"{' ' * len(gutter)} {'^' * max(1, len(text.strip()))}", file=sys.stderr)
        print("", file=sys.stderr)
    for i, line in enumerate(str(exc).splitlines()):
        print(f"  {'configure: error: ' if i == 0 else '                  '}{line}",
              file=sys.stderr)
    print("", file=sys.stderr)


