def deep_merge(base: dict, over: dict, path: str = "") -> dict:
    out = dict(base)
    for k, v in over.items():
        here = f"{path}.{k}" if path else k
        if k not in base:
            raise ConfigError(f"unknown key [{here}] in raylib_multiplatform.toml")
        if isinstance(base[k], dict) and isinstance(v, dict):
            # [ios.settings] is a free-form passthrough; do not police its keys.
            out[k] = v if here == "ios.settings" else deep_merge(base[k], v, here)
        else:
            out[k] = v
    return out


def load_config() -> dict:
    if not TOML.exists():
        warn("raylib_multiplatform.toml not found — using defaults.\n"
             "         Create it to name your game and set your app ids. "
             "See README.md.")
        return json.loads(json.dumps(DEFAULTS))
    with TOML.open("rb") as fh:
        try:
            user = tomllib.load(fh)
        except tomllib.TOMLDecodeError as e:
            raise ConfigError(f"raylib_multiplatform.toml is not valid TOML: {e}") from None
    return deep_merge(DEFAULTS, user)


