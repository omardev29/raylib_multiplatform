def frozen_versions() -> dict[str, str]:
    """The ```versions block of thirdparty/FROZEN_VERSIONS.md.

    Same block tools/versions_check.sh enforces, so the docs, the checker and
    the generator cannot disagree about what is pinned.
    """
    md = REPO / "thirdparty" / "FROZEN_VERSIONS.md"
    out: dict[str, str] = {}
    inside = False
    for line in md.read_text(encoding="utf-8").splitlines():
        if line.strip() == "```versions":
            inside = True
            continue
        if inside and line.strip() == "```":
            break
        if inside:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(None, 1)
            if len(parts) == 2:
                out[parts[0]] = parts[1].strip()
    if not out:
        raise ConfigError(f"no ```versions block found in {md}")
    return out


def expand_targets(enabled: list[str], disabled: list[str]) -> list[str]:
    """Groups expand and deduplicate, then `disabled` is subtracted.

    Deliberately order-independent and conflict-free: there is no precedence to
    reason about, so `enabled = ["all"], disabled = ["ios"]` means exactly what
    it looks like.
    """
    def resolve(names: list[str], where: str) -> set[str]:
        out: set[str] = set()
        for n in names:
            if n in GROUPS:
                out.update(GROUPS[n])
            elif n in TARGETS:
                out.add(n)
            else:
                known = ", ".join(sorted(set(GROUPS) | set(TARGETS)))
                raise ConfigError(
                    f"[targets] {where}: unknown target or group {n!r}.\nKnown: {known}")
        return out

    result = sorted(resolve(enabled, "enabled") - resolve(disabled, "disabled"),
                    key=list(TARGETS).index)
    if not result:
        raise ConfigError("[targets]: nothing left to build. `enabled` minus `disabled` is empty.")
    return result


def admob_on(cfg: dict, targets: list[str]) -> bool:
    """Is AdMob part of this build?

    Two ways to say no, and the second one is the one nobody remembers to say.
    Turning Android off in [targets] — by name or through a group like
    "mobile" — means there is no Android build to put ads in, so carrying the
    Google Mobile Ads SDK, the AD_ID permission and the Play "advertising ID"
    declaration that comes with it would be paying for nothing.
    """
    return bool(cfg["android"]["admob"]["enabled"]) and "android" in targets


