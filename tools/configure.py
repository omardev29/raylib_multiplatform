MODULE_FLAG = {
    "rshapes": "SUPPORT_MODULE_RSHAPES",
    "rtextures": "SUPPORT_MODULE_RTEXTURES",
    "rtext": "SUPPORT_MODULE_RTEXT",
    "rmodels": "SUPPORT_MODULE_RMODELS",
    "raudio": "SUPPORT_MODULE_RAUDIO",
}


def parse_raylib_config() -> dict[str, int]:
    """Read every SUPPORT_* flag and its real value out of raylib's config.h.

    We do NOT use raylib's own CMake options. They only take effect when
    CUSTOMIZE_BUILD=ON, and turning that on flips roughly fifteen flags that are
    `0` in config.h to ON, because cmake/ParseConfigHeader.cmake maps any
    uncommented #define to ON without looking at its value. Defining
    EXTERNAL_CONFIG_FLAGS and supplying the complete set ourselves is the only
    way to get what the config actually says.

    Because we supply the complete set, a flag we fail to parse would be
    undefined, and `#if SUPPORT_X` treats undefined as 0 — silently disabling a
    feature nobody asked to disable. Hence the sanity checks below.
    """
    header = REPO / "thirdparty" / "raylib" / "src" / "config.h"
    if not header.exists():
        raise ConfigError(f"{header} not found (is the raylib submodule checked out?)")

    text = header.read_text(encoding="utf-8", errors="replace")
    start = text.find("#if !defined(EXTERNAL_CONFIG_FLAGS)")
    end = text.find("#endif // !EXTERNAL_CONFIG_FLAGS")
    if start < 0 or end < 0:
        raise ConfigError(
            "could not find the EXTERNAL_CONFIG_FLAGS guard in raylib's config.h. "
            "raylib's layout changed; tools/configure.py needs updating.")
    guarded = text[start:end]

    flags: dict[str, int] = {}
    unrepresentable: list[str] = []
    for line in guarded.splitlines():
        stripped = line.strip()
        if stripped.startswith("//"):
            continue  # commented out: raylib's own sources supply the default
        if not stripped.startswith("#define"):
            continue
        m = re.match(r"#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(-?\d+)\s*(//.*)?$", stripped)
        if m:
            # Everything inside the guard is passed through, not just SUPPORT_*.
            # Defining EXTERNAL_CONFIG_FLAGS skips the whole block, so a value we
            # fail to carry over (RLGL_SHOW_GL_DETAILS_INFO, say) would silently
            # become 0 and change the engine's behaviour.
            flags[m.group(1)] = int(m.group(2))
            continue
        name = re.match(r"#define\s+([A-Za-z_][A-Za-z0-9_]*)", stripped)
        unrepresentable.append(name.group(1) if name else stripped)

    if unrepresentable:
        raise ConfigError(
            "raylib's config.h defines values inside the EXTERNAL_CONFIG_FLAGS guard that this "
            "generator cannot carry over as integers:\n  " + ", ".join(unrepresentable) +
            "\nUpdate tools/configure.py to pass them through, or they will be silently lost.")

    for required in MODULE_FLAG.values():
        if required not in flags:
            raise ConfigError(f"{required} not found in raylib's config.h — "
                              "raylib's layout changed; tools/configure.py needs updating.")
    return flags


def raylib_defs(cfg: dict) -> tuple[list[str], list[str]]:
    """(compile definitions, extra source files needed to keep the link valid)."""
    flags = parse_raylib_config()
    for mod in cfg["raylib"]["disabled_modules"]:
        flags[MODULE_FLAG[mod]] = 0

    defs = ["EXTERNAL_CONFIG_FLAGS"] + [f"{k}={v}" for k, v in sorted(flags.items())]

    # Disabling raudio leaves the asset layer referencing symbols that no longer
    # exist: assets::LoadSound calls LoadWaveFromMemory, LoadSoundFromWave,
    # UnloadWave and raylib's own LoadSound, and rres-raylib.h compiles audio
    # loaders regardless of which raylib modules are on.
    #
    # GNU ld hides this. It garbage-collects the unreachable sections before it
    # complains, so a Linux build of `disabled_modules = ["raudio"]` links
    # cleanly. Apple's ld64 resolves undefined symbols BEFORE dead-stripping, so
    # the identical config fails on macOS and iOS only. Stubs cost nothing and
    # work on every linker.
    stubs = ["raudio"] if "raudio" in cfg["raylib"]["disabled_modules"] else []
    return defs, stubs


STUB_SOURCE = """/* {header}
 *
 * [raylib] disabled_modules = ["raudio"] removes these from libraylib, but the
 * template's asset layer still refers to them — assets::LoadSound decodes a
 * Wave and turns it into a Sound, and rres-raylib.h compiles audio loaders
 * whatever the module flags say.
 *
 * They have to resolve even though nothing reachable calls them: Apple's ld64
 * errors on undefined symbols before it ever dead-strips them, so without this
 * file the config that links fine on Linux fails on macOS and iOS only.
 *
 * raylib.h supplies the real types, so these cannot drift out of ABI with the
 * declarations they are standing in for.
 */
#include <raylib.h>

Wave LoadWaveFromMemory(const char *fileType, const unsigned char *fileData, int dataSize)
{{
    (void)fileType; (void)fileData; (void)dataSize;
    Wave empty = {{0}};
    return empty;
}}

Sound LoadSoundFromWave(Wave wave)
{{
    (void)wave;
    Sound empty = {{0}};
    return empty;
}}

Sound LoadSound(const char *fileName)
{{
    (void)fileName;
    Sound empty = {{0}};
    return empty;
}}

void UnloadWave(Wave wave)
{{
    (void)wave;
}}
"""


