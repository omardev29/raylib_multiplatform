def one_of(value, allowed: set[str], where: str, extra: str = "") -> None:
    """`where` must be one of `allowed`, and it must be a string first.

    THE TYPE CHECK IS THE POINT. `x not in some_set` raises TypeError when x is a
    list or a table, and TOML hands those over happily — `backend = ["glfw"]` is
    a typo anyone can make. Every membership check in this file went through
    that hole and answered a config mistake with a Python traceback, which is
    the opposite of the rule in CLAUDE.md. Found by a test that tried a list
    because a list is a thing that exists, not because anything suggested it.
    """
    options = ", ".join(sorted(allowed))
    if not isinstance(value, str):
        raise ConfigError(
            f"{where} = {value!r} has to be a string, one of {options}.\n"
            "A TOML array or table here is almost always a stray pair of brackets.")
    if value not in allowed:
        message = f"{where} has to be one of {options}, got {value!r}."
        raise ConfigError(message + (f"\n{extra}" if extra else ""))


