def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def cmake_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def gen_cmake(cfg: dict) -> None:
    name = cfg["project"]["name"]
    write(REPO / "cmake" / "generated" / "project.cmake", f"""# {GEN_HEADER}
set(TEMPLATE_PROJECT_NAME "{cmake_escape(name)}")
set(TEMPLATE_RRES_PASSWORD "{cmake_escape(cfg['resources']['rres_password'])}")
""")

    defs, stubs = raylib_defs(cfg)
    stub_path = REPO / "cmake" / "generated" / "module_stubs.c"
    if stubs:
        write(stub_path, STUB_SOURCE.format(header=GEN_HEADER))
    elif stub_path.exists():
        stub_path.unlink()

    lines = [f"# {GEN_HEADER}",
             "#",
             "# The complete flag set, passed with EXTERNAL_CONFIG_FLAGS so raylib's own",
             "# config.h defaults are bypassed. Every flag must be here: `#if SUPPORT_X`",
             "# treats an undefined macro as 0.",
             "set(RAYLIB_CONFIG_DEFS"]
    lines += [f"    {d}" for d in defs]
    lines.append(")")
    lines.append('set(RAYLIB_STUB_SOURCES "{}")'.format(
        '${CMAKE_CURRENT_LIST_DIR}/module_stubs.c' if stubs else ""))
    write(REPO / "cmake" / "generated" / "raylib_flags.cmake", "\n".join(lines) + "\n")

    # Dev toolchain. Only ever included for non-production builds, so CI (which
    # builds `release`/`web`) is untouched by anything in [dev].
    dev = [f"# {GEN_HEADER}",
           "#",
           "# Local development only. The release and web presets never include this.",
           ""]
    compiler = cfg["dev"]["compiler"]
    if compiler != "default":
        cc, cxx = ("clang", "clang++") if compiler == "clang" else ("gcc", "g++")
        dev += [
            f"find_program(_TPL_CC  {cc})",
            f"find_program(_TPL_CXX {cxx})",
            "if(_TPL_CC AND _TPL_CXX)",
            '  set(CMAKE_C_COMPILER   "${_TPL_CC}"  CACHE FILEPATH "" FORCE)',
            '  set(CMAKE_CXX_COMPILER "${_TPL_CXX}" CACHE FILEPATH "" FORCE)',
            "else()",
            f'  message(STATUS "[dev] compiler = {compiler} requested but not found; '
            'using the system default")',
            "endif()",
            "",
        ]
    linker = cfg["dev"]["linker"]
    if linker != "default":
        candidates = {"auto": ["mold", "lld"], "mold": ["mold"], "lld": ["lld"]}[linker]
        dev += [
            "# A faster linker is the single biggest win on an incremental debug build.",
            "# CMAKE_LINKER_TYPE needs CMake 3.29+; the project already requires 3.30.",
            f"foreach(_ld {' '.join(candidates)})",
            "  find_program(_TPL_LD_${_ld} ${_ld})",
            "  if(_TPL_LD_${_ld})",
            "    string(TOUPPER ${_ld} _TPL_LD_TYPE)",
            '    set(CMAKE_LINKER_TYPE ${_TPL_LD_TYPE})',
            '    message(STATUS "[dev] linker: ${_ld}")',
            "    break()",
            "  endif()",
            "endforeach()",
        ]
    write(REPO / "cmake" / "generated" / "dev_toolchain.cmake", "\n".join(dev) + "\n")


