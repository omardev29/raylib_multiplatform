def _print_matrix(cfg: dict, family: str) -> None:
    targets = expand_targets(cfg["targets"]["enabled"], cfg["targets"]["disabled"])
    if family != "bsd":
        raise ConfigError(f"--print-matrix: only 'bsd' has a matrix (got {family!r})")
    pins = frozen_versions()
    include = []
    for t in targets:
        if t not in BSD_LEGS:
            continue
        leg = dict(BSD_LEGS[t], target=t)
        key = leg["os"]
        if key not in pins:
            raise ConfigError(f"FROZEN_VERSIONS.md has no `{key}` entry, "
                              "which the BSD matrix needs for its OS version.")
        leg["version"] = pins[key]
        include.append(leg)
    print(json.dumps({"include": include}, separators=(",", ":")))


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    ap.add_argument("--strict-release", action="store_true",
                    help="also reject placeholder identifiers (used on tag builds)")
    ap.add_argument("--print-name", action="store_true")
    ap.add_argument("--print-targets", action="store_true")
    ap.add_argument("--print-families", action="store_true",
                    help="CI families with at least one enabled target")
    ap.add_argument("--print-matrix", metavar="FAMILY")
    ap.add_argument("--print-config", action="store_true")
    ap.add_argument("--print-stamp", action="store_true")
    ap.add_argument("--make-default-icon", action="store_true")
    args = ap.parse_args(argv)

    if args.make_default_icon:
        make_default_icon()
        return 0

    cfg = load_config()
    validate(cfg, strict_release=args.strict_release)
    targets = expand_targets(cfg["targets"]["enabled"], cfg["targets"]["disabled"])

    if args.print_name:
        print(cfg["project"]["name"])
        return 0
    if args.print_targets:
        print(json.dumps(targets, separators=(",", ":")))
        return 0
    if args.print_families:
        print(json.dumps(sorted({TARGETS[t][0] for t in targets}), separators=(",", ":")))
        return 0
    if args.print_matrix:
        _print_matrix(cfg, args.print_matrix)
        return 0
    if args.print_stamp:
        print(compute_stamp())
        return 0
    if args.print_config:
        version_name, version_code = resolve_version()
        print(json.dumps({
            "config": cfg, "targets": targets,
            "families": sorted({TARGETS[t][0] for t in targets}),
            "version_name": version_name, "version_code": version_code,
        }, indent=2, sort_keys=True))
        return 0
    if args.check:
        print(f"configure: OK — {cfg['project']['name']}, {len(targets)} target(s)")
        return 0

    gen_cmake(cfg)
    gen_app_config(cfg)
    gen_gradle_properties(cfg)
    generate_icons(cfg)
    gen_ios_project(cfg)   # after icons: it references the asset catalog if present
    STAMP.parent.mkdir(parents=True, exist_ok=True)
    STAMP.write_text(compute_stamp() + "\n")

    version_name, _ = resolve_version()
    print(f"configure: {cfg['project']['name']} {version_name} — "
          f"{len(targets)} target(s): {' '.join(targets)}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except ConfigError as exc:
        print(f"\nconfigure: error: {exc}\n", file=sys.stderr)
        sys.exit(1)
