def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def cmake_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def gen_cmake(cfg: dict) -> None:
    name = cfg["project"]["name"]
    web = cfg["web"]
    # TOTAL_MEMORY has to be a multiple of 64 KiB and Emscripten rejects it
    # otherwise, so megabytes are what the config asks for and the arithmetic
    # happens here rather than in anyone's head.
    total_memory = int(web["memory"]) * 1024 * 1024
    grow = "1" if web["grow"] else "0"
    write(REPO / "cmake" / "generated" / "project.cmake", f"""# {GEN_HEADER}
set(TEMPLATE_PROJECT_NAME "{cmake_escape(name)}")
set(TEMPLATE_RRES_PASSWORD "{cmake_escape(cfg['resources']['rres_password'])}")
set(TEMPLATE_WEB_TOTAL_MEMORY {total_memory})
set(TEMPLATE_WEB_ALLOW_MEMORY_GROWTH {grow})
set(TEMPLATE_WEB_BACKEND "{cfg["web"]["backend"]}")
set(TEMPLATE_WINDOWS_BACKEND "{cfg["windows"]["backend"]}")
set(TEMPLATE_LINUX_BACKEND "{cfg["linux"]["backend"]}")
set(TEMPLATE_LINUX_WAYLAND {"ON" if cfg["linux"]["wayland"] else "OFF"})
""")

    defs, stubs = raylib_defs(cfg)
    stub_path = REPO / "cmake" / "generated" / "module_stubs.c"
    if stubs:
        write(stub_path, STUB_SOURCE.format(header=GEN_HEADER))
    elif stub_path.exists():
        stub_path.unlink()

    lines = [f"# {GEN_HEADER}",
             "#",
             "# The complete flag set, passed with EXTERNAL_CONFIG_FLAGS so raylib's own",
             "# config.h defaults are bypassed. Every flag must be here: `#if SUPPORT_X`",
             "# treats an undefined macro as 0.",
             "set(RAYLIB_CONFIG_DEFS"]
    lines += [f"    {d}" for d in defs]
    lines.append(")")
    lines.append('set(RAYLIB_STUB_SOURCES "{}")'.format(
        '${CMAKE_CURRENT_LIST_DIR}/module_stubs.c' if stubs else ""))
    write(REPO / "cmake" / "generated" / "raylib_flags.cmake", "\n".join(lines) + "\n")

    # Dev toolchain. Only ever included for non-production builds, so CI (which
    # builds `release`/`web`) is untouched by anything in [dev].
    dev = [f"# {GEN_HEADER}",
           "#",
           "# Local development only. The release and web presets never include this.",
           ""]
    compiler = cfg["dev"]["compiler"]
    if compiler != "default":
        # Several names per compiler, because the one that works depends on how
        # it was installed. MinGW in particular is almost never plain `gcc` on
        # Windows: MSYS2 ships x86_64-w64-mingw32-gcc, and picking up a stray
        # `gcc` from a Git-for-Windows shell is how you end up with a build that
        # asks for X11 on Windows.
        names = {
            "clang": (["clang"], ["clang++"]),
            "gcc":   (["gcc"], ["g++"]),
            "mingw": (["x86_64-w64-mingw32-gcc", "gcc"],
                      ["x86_64-w64-mingw32-g++", "g++"]),
            "msvc":  (["cl"], ["cl"]),
        }[compiler]
        cc, cxx = " ".join(names[0]), " ".join(names[1])
        # mingw and msvc are Windows toolchains, and asking for them anywhere
        # else is a mistake worth catching rather than obeying. A Linux box with
        # the mingw cross-compiler installed would otherwise find
        # x86_64-w64-mingw32-gcc and quietly start producing .exe files from a
        # native build.
        if compiler in ("mingw", "msvc"):
            # MSYS and CYGWIN as well as WIN32, and that is not belt-and-braces:
            # in MSYS2's MSYS environment CMake targets the POSIX layer and sets
            # MSYS and UNIX, NOT WIN32. So this fired on an actual Windows
            # machine to say that mingw only makes sense on Windows — which is
            # both wrong and, standing in MSYS2 where x86_64-w64-mingw32-gcc is
            # right there, quite hard to argue with.
            dev += ['if(NOT WIN32 AND NOT MSYS AND NOT CYGWIN)',
                    f'  message(FATAL_ERROR "[dev] compiler = {compiler} only makes sense on '
                    f'Windows. On this platform use clang, gcc or default.")',
                    "endif()"]
        dev += [
            f"find_program(_TPL_CC  NAMES {cc})",
            f"find_program(_TPL_CXX NAMES {cxx})",
            "if(_TPL_CC AND _TPL_CXX)",
            '  set(CMAKE_C_COMPILER   "${_TPL_CC}"  CACHE FILEPATH "" FORCE)',
            '  set(CMAKE_CXX_COMPILER "${_TPL_CXX}" CACHE FILEPATH "" FORCE)',
            "  # The breadcrumb the release configure looks for. Those two are",
            "  # FORCEd into the cache and stay there; a later release preset on",
            "  # the same build directory would inherit them silently, so it",
            "  # refuses instead. See the RMP_DEV_COMPILER check in CMakeLists.txt.",
            '  set(RMP_DEV_COMPILER "${_TPL_CC}" CACHE INTERNAL "")',
            "else()",
            f'  message(STATUS "[dev] compiler = {compiler} requested but not found; '
            'using the system default")',
            "endif()",
            "",
        ]
    write(REPO / "cmake" / "generated" / "dev_toolchain.cmake", "\n".join(dev) + "\n")
    gen_dev_linker(cfg)


# The linker is its own generated file, and its own include, for a reason that
# is not tidiness: choosing one has to be VERIFIED, and verifying means linking
# a test program, which needs a working compiler — so it cannot happen before
# project(). dev_toolchain.cmake runs before, this one after.
def gen_dev_linker(cfg: dict) -> None:
    linker = cfg["dev"]["linker"]
    lines = [f"# GENERATED by tools/configure.py from {TOML.name} — do not edit.",
             "#",
             "# Local development only. Included AFTER project(), because picking a",
             "# linker means checking that it actually links.",
             ""]

    # mold is ELF-only, by its own account: `mold --help` prints
    # "supported targets: elf32-i386 elf64-x86-64 ..." and no PE/COFF or Mach-O.
    # So `auto` must not offer it where it cannot work — finding the binary is
    # not the same as being able to use it, and on MSYS2 the difference showed
    # up as a link error about `ld` with the word mold nowhere in it.
    candidates = {"auto": ["mold", "lld"], "mold": ["mold"], "lld": ["lld"]}.get(linker, [])

    if not candidates:
        lines.append('message(STATUS "[dev] linker: the platform default")')
    else:
        lines += [
            "# find_program() says a binary exists. check_linker_flag() says the",
            "# toolchain can actually USE it — which is a different question, and the",
            "# one that matters: GCC's -fuse-ld=lld needs an `ld.lld` driver on PATH,",
            "# not just `lld`, and MSYS2 ships one without the other. Guessing there",
            "# produced a build that configured cleanly and then failed to link with a",
            "# message about `ld` that named neither lld nor this setting.",
            "include(CheckLinkerFlag)",
            "set(_rmp_ld_chosen OFF)",
            f"foreach(_ld {' '.join(candidates)})",
            "  if(_rmp_ld_chosen)",
            "    break()",
            "  endif()",
            "  # mold cannot emit PE/COFF or Mach-O at all, so do not even look for it",
            "  # there. This is what keeps `auto` from being a coin toss off Linux.",
            '  if(_ld STREQUAL "mold" AND (WIN32 OR MSYS OR CYGWIN OR APPLE))',
            "    continue()",
            "  endif()",
            "  find_program(_rmp_ld_bin_${_ld} ${_ld})",
            "  if(_rmp_ld_bin_${_ld})",
            '    check_linker_flag(CXX "-fuse-ld=${_ld}" _rmp_ld_works_${_ld})',
            "    if(_rmp_ld_works_${_ld})",
            '      add_link_options("-fuse-ld=${_ld}")',
            '      message(STATUS "[dev] linker: ${_ld}")',
            "      set(_rmp_ld_chosen ON)",
            "    endif()",
            "  endif()",
            "endforeach()",
            "",
            "if(NOT _rmp_ld_chosen)",
        ]
        if linker == "auto":
            # auto never fails. It is a speed setting, and a speed setting that
            # can stop a build is worse than a slow build.
            lines += ['  message(STATUS "[dev] linker: the platform default '
                      '(no faster one usable here)")']
        else:
            lines += [
                f'  message(WARNING "[dev] linker = \\"{linker}\\" was asked for and this '
                'toolchain cannot use it — "',
                '                  "either it is not installed, or -fuse-ld does not reach '
                'it (GCC needs an "',
                '                  "ld.lld on PATH, not just lld). Falling back to the '
                'platform default. "',
                '                  "Set [dev] linker = \\"auto\\" to stop being asked '
                'about it.")',
            ]
        lines.append("endif()")

    write(REPO / "cmake" / "generated" / "dev_linker.cmake", "\n".join(lines) + "\n")


