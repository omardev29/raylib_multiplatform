def validate(cfg: dict, strict_release: bool) -> None:
    for key in ("enabled", "disabled"):
        value = cfg["upx"][key]
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            raise ConfigError(f"[upx] {key} has to be a list of strings, got {value!r}")

    # bool first: in Python `True` is an int, and `max_size_mb = true` in the
    # TOML would otherwise sail through as 1 MB and skip every binary you have.
    cap = cfg["upx"]["max_size_mb"]
    if isinstance(cap, bool) or not isinstance(cap, int):
        raise ConfigError(f"[upx] max_size_mb has to be a whole number of "
                          f"megabytes, got {cap!r}")
    if cap < 1:
        raise ConfigError(
            f"[upx] max_size_mb = {cap} would skip every binary. To turn "
            "compression off, empty `enabled` instead — that says what you mean.")
    if cap > UPX_HARD_LIMIT_MB:
        raise ConfigError(
            f"[upx] max_size_mb = {cap} is above the {UPX_HARD_LIMIT_MB} MB that "
            "UPX itself refuses to go past, so the packer would fail the build "
            "instead of skipping the file. Lower it.")

    one_of(cfg["windows"]["backend"], WINDOWS_BACKENDS, "[windows] backend")
    # Combinations. Each of these is a pair of keys that are individually valid
    # and cannot both be honoured, so the build would silently do one of the two
    # things you asked for. Caught here rather than in CMake, because a
    # configuration error should not cost a compile — and on CI it should not
    # cost a runner.
    if cfg["linux"]["backend"] == "rgfw" and cfg["linux"]["wayland"]:
        raise ConfigError(
            "[linux] backend = \"rgfw\" and wayland = true cannot both hold.\n"
            "RGFW's Linux backend is X11-only — it reports itself as "
            "\"DESKTOP (RGFW - X11)\" — and the wayland switch only reaches GLFW.\n"
            "Leaving it would build an X11 binary while the config said Wayland.\n"
            "Pick one: backend = \"glfw\" to get native Wayland, or wayland = false.")

    one_of(cfg["linux"]["backend"], LINUX_BACKENDS, "[linux] backend",
           "For native Wayland keep backend = \"glfw\" and set wayland = true.")
    if not isinstance(cfg["linux"]["wayland"], bool):
        raise ConfigError("[linux] wayland has to be true or false")

    # [linux] glibc — the oldest glibc the shipped binary is allowed to need.
    #
    # It is a FLOOR, not a wish: tools/glibc_check.sh reads the symbol versions
    # out of the built binary and fails if any of them is newer. Building on
    # ubuntu-24.04 gives you glibc 2.39 by default, and a binary that needs 2.39
    # does not start on Debian 12, Ubuntu 22.04, RHEL 8 or inside Steam's
    # runtime — none of which is visible until somebody tries.
    glibc = cfg["linux"]["glibc"]
    if not isinstance(glibc, str):
        raise ConfigError(f"[linux] glibc = {glibc!r} has to be a string like \"2.28\", "
                          "or \"\" to build with whatever the host has.")
    if glibc and not re.match(r"^2\.(1[7-9]|[2-9][0-9])$", glibc):
        raise ConfigError(
            f"[linux] glibc = {glibc!r} is not a version this can target.\n"
            "Use 2.17 to 2.99, or \"\" to build against the host's glibc and target "
            "nothing in particular.\n"
            "2.17 is RHEL 7, 2.28 is RHEL 8 and Debian 10, 2.31 is Ubuntu 20.04, "
            "Debian 11 and Steam's sniper runtime.")
    one_of(cfg["dev"]["compiler"], COMPILERS, "[dev] compiler")

    web_memory = cfg["web"]["memory"]
    if not isinstance(web_memory, int) or web_memory < 16 or web_memory > 4096:
        raise ConfigError(
            f"[web] memory = {web_memory!r} has to be a whole number of megabytes between "
            "16 and 4096. Below 16 nothing loads; above 4096 is past what a 32-bit wasm "
            "module can address at all.")
    if not isinstance(cfg["web"]["grow"], bool):
        raise ConfigError("[web] grow has to be true or false")
    # isinstance first, and the reason is one line up in this file's history:
    # `x in some_dict` raises TypeError on an unhashable value exactly the way
    # `x in some_set` does, and backend = ["glfw"] is a typo a TOML can hold.
    # ConfigureMembershipTest caught this within a minute of it being written,
    # which is the entire point of that class.
    if isinstance(cfg["web"]["backend"], str) and cfg["web"]["backend"] in WEB_REFUSED:
        raise ConfigError(
            f"[web] backend = {cfg['web']['backend']!r} cannot work here.\n"
            f"{WEB_REFUSED[cfg['web']['backend']]}\n"
            f"Use one of {', '.join(sorted(WEB_BACKENDS))}.")
    one_of(cfg["web"]["backend"], WEB_BACKENDS, "[web] backend",
           "It names what raylib talks to, not what compiles the code — Emscripten "
           "compiles it either way.")

    name = cfg["project"]["name"]
    if not NAME_RE.match(name):
        raise ConfigError(
            f"[project] name = {name!r} is not usable as a filename.\n"
            "Use letters, digits, '_' and '-', starting with a letter. It becomes the "
            "executable name on five operating systems.")

    if "\n" in cfg["window"]["title"] or "\r" in cfg["window"]["title"]:
        raise ConfigError("[window] title must be a single line: it becomes a Java "
                          ".properties value and an Xcode build setting.")

    orient = cfg["window"]["orientation"]
    if orient not in ("landscape", "portrait", "unspecified"):
        raise ConfigError(f"[window] orientation = {orient!r} must be "
                          "'landscape', 'portrait' or 'unspecified'.")
    for k in ("width", "height"):
        v = cfg["window"][k]
        if not isinstance(v, int) or not (16 <= v <= 16384):
            raise ConfigError(f"[window] {k} = {v!r} must be an integer between 16 and 16384.")

    # android:appCategory, which is how Play files your app. These are the only
    # values Android accepts; anything else makes the manifest merger fail deep
    # inside the Gradle build with a message nobody can act on.
    #
    # This key used to be written into the launcher <intent-filter> instead,
    # where the only value that works is LAUNCHER. Setting it to anything else
    # produced an APK that installed and then had no icon anywhere on the
    # device — see the comment in raymob/app/AndroidManifest.template.xml.
    APP_CATEGORIES = {"game", "audio", "video", "image", "social", "news",
                      "maps", "productivity", "accessibility"}
    category = str(cfg["android"]["category"]).lower()
    if category not in APP_CATEGORIES:
        raise ConfigError(
            f"[android] category = {cfg['android']['category']!r} is not an Android app "
            f"category.\nUse one of: {', '.join(sorted(APP_CATEGORIES))}.\n"
            "It becomes android:appCategory, which is how the Play Store files your app. "
            "It is NOT the launcher intent category — that one is fixed, because an app "
            "without it has no icon.")
    cfg["android"]["category"] = category

    # Every Android switch is a boolean, and TOML will happily hand us the
    # string "false", which is truthy. Java .properties would then receive
    # "false" for a value nobody checked, which is how a switch silently stops
    # switching.
    for table in ("display", "permissions", "features"):
        for k, v in cfg["android"][table].items():
            if not isinstance(v, bool):
                raise ConfigError(f"[android.{table}] {k} = {v!r} must be true or false.")
    if not isinstance(cfg["android"]["admob"]["enabled"], bool):
        raise ConfigError("[android.admob] enabled = "
                          f"{cfg['android']['admob']['enabled']!r} must be true or false.")

    appid = cfg["android"]["application_id"]
    if not APPID_RE.match(appid):
        raise ConfigError(
            f"[android] application_id = {appid!r} is not a valid Android application id.\n"
            "It needs at least one dot and each segment must start with a letter, "
            "e.g. com.yourname.yourgame.")
    # The Gradle preBuild hook rewrites sources by string-substituting this id and
    # reverts them afterwards. A value containing the search string makes the
    # revert non-idempotent and permanently mangles thirdparty/raymob/*.c.
    if "com.raylib.raymob" in appid:
        raise ConfigError(
            f"[android] application_id = {appid!r} must not contain 'com.raylib.raymob'.\n"
            "Gradle rewrites and then reverts that exact string in the raymob sources; "
            "an id containing it corrupts them.")

    bundle = cfg["ios"]["bundle_id"]
    if not BUNDLE_RE.match(bundle):
        raise ConfigError(
            f"[ios] bundle_id = {bundle!r} is not a valid bundle identifier.\n"
            "It needs at least one dot, e.g. com.yourname.yourgame.")

    if not re.match(r"^\d+\.\d+(\.\d+)?$", str(cfg["ios"]["deployment_target"])):
        raise ConfigError(f"[ios] deployment_target = {cfg['ios']['deployment_target']!r} "
                          "must look like \"15.6\".")

    if cfg["android"]["gl_version"] not in ("ES20", "ES30", "ES31", "ES32"):
        raise ConfigError(f"[android] gl_version = {cfg['android']['gl_version']!r} must be one "
                          "of ES20, ES30, ES31, ES32.")

    min_sdk = cfg["android"]["min_sdk"]
    if not isinstance(min_sdk, int) or not (21 <= min_sdk <= 36):
        raise ConfigError(f"[android] min_sdk = {min_sdk!r} must be an integer between 21 and 36.")

    for mod in cfg["raylib"]["disabled_modules"]:
        if mod in PROTECTED_MODULES:
            raise ConfigError(
                f"[raylib] disabled_modules: {mod!r} cannot be disabled — "
                f"{PROTECTED_MODULES[mod]}.")
        if mod not in OPTIONAL_MODULES:
            raise ConfigError(
                f"[raylib] disabled_modules: unknown module {mod!r}. "
                f"Optional modules are: {', '.join(sorted(OPTIONAL_MODULES))}.")

    # [dev] compiler is checked at the top of this function, against COMPILERS.
    # There used to be a second check here allowing only clang/gcc/default, and
    # the two disagreed the moment mingw and msvc were added — which is exactly
    # what tests/configure_test.py caught.
    if cfg["dev"]["linker"] not in ("auto", "mold", "lld", "default"):
        raise ConfigError("[dev] linker must be 'auto', 'mold', 'lld' or 'default'.")

    # mingw and msvc are Windows toolchains, and [dev] is local development only
    # — CI builds the release preset, which never reads this section. On Linux,
    # asking for mingw finds the cross-compiler and quietly produces a .exe you
    # cannot run; asking for msvc finds nothing and falls back.
    #
    # CMake already refuses this, and that refusal stays as the backstop. It is
    # ALSO here because a configuration mistake is not allowed to cost a
    # configure step: by the time CMake speaks, raylib is already being detected.
    if cfg["dev"]["compiler"] in ("mingw", "msvc") and not on_windows():
        raise ConfigError(
            f"[dev] compiler = {cfg['dev']['compiler']!r} is a Windows toolchain, and this "
            f"is {platform.system()}.\n"
            "It is for local development, and CI never reads this section — so it can only "
            "mean this machine.\n"
            "Use \"clang\", \"gcc\" or \"default\" here. Cross-compiling for Windows is what "
            "the windows-x64 target does, from [targets].")

    # mold links ELF and nothing else. Its own --help says so:
    #
    #   mold: supported targets: elf32-i386 elf64-x86-64 elf32-littlearm ...
    #
    # No PE/COFF, no Mach-O. On Windows and macOS it is not "probably fine" or
    # "slower" — it cannot produce the file. Asking for it there used to get as
    # far as the linker, which then failed with a message about ld, and the word
    # mold appeared nowhere in it.
    if cfg["dev"]["linker"] == "mold" and (on_windows() or on_macos()):
        where = "Windows" if on_windows() else "macOS"
        raise ConfigError(
            f"[dev] linker = \"mold\" cannot work on {where}. mold links ELF only — its own "
            "--help lists elf32-i386, elf64-x86-64 and friends, and no PE/COFF or Mach-O.\n"
            "Use \"lld\", or \"auto\" to let the build pick whatever actually links here.")

    bg = cfg["icon"]["adaptive_background"]
    if bg and not re.match(r"^#[0-9a-fA-F]{6}$", bg):
        raise ConfigError(f"[icon] adaptive_background = {bg!r} must be #RRGGBB, or \"\".")

    # These reach the workflows through $GITHUB_OUTPUT as key=value lines, so the
    # charsets are deliberately tight: a newline in any of them would let the
    # config file define arbitrary job outputs.
    for key, value, pattern, shape in (
        ("[deploy.itch] user", cfg["deploy"]["itch"]["user"], r"^[A-Za-z0-9_-]*$", "an itch.io username"),
        ("[deploy.itch] game", cfg["deploy"]["itch"]["game"], r"^[A-Za-z0-9_-]*$", "an itch.io game slug"),
        ("[deploy.firebase] project_id", cfg["deploy"]["firebase"]["project_id"],
         r"^[a-z0-9-]*$", "a GCP project id (lowercase, digits, hyphens)"),
        ("[deploy.firebase] device", cfg["deploy"]["firebase"]["device"],
         r"^[A-Za-z0-9_.,=-]*$", "a gcloud device spec, e.g. model=MediumPhone.arm,version=33"),
    ):
        if not isinstance(value, str) or not re.match(pattern, value):
            raise ConfigError(f"{key} = {value!r} must be {shape}, or \"\".")

    # Half-configured is worse than not configured, because the workflow reads
    # both and skips silently when either is empty — so a deploy that was meant
    # to happen simply does not, and nothing says why until somebody looks for
    # the build that never appeared.
    itch = cfg["deploy"]["itch"]
    if bool(itch["user"]) != bool(itch["game"]):
        missing = "game" if itch["user"] else "user"
        raise ConfigError(
            f"[deploy.itch] user and game go together, and {missing} is empty.\n"
            "The itch job needs both to build the target `user/game:channel`, so with one "
            "of them missing it skips and the release is never pushed.\n"
            f"Set {missing}, or clear both to turn itch.io deployment off.",
            ("deploy.itch", missing))

    dead = cfg["input"]["deadzone"]
    if isinstance(dead, bool) or not isinstance(dead, (int, float)):
        raise ConfigError(f"[input] deadzone = {dead!r} has to be a number between 0 and 0.95.")
    if not (0.0 <= dead <= 0.95):
        raise ConfigError(
            f"[input] deadzone = {dead} has to be between 0 and 0.95.\n"
            "It is the fraction of a stick's travel that reads as zero. 0 turns it off, "
            "which on a worn controller means the character walks on its own; past 0.95 "
            "there is almost no travel left to read.")

    ui = cfg["ui"]
    one_of(ui["theme"], UI_THEMES, "[ui] theme",
           "It only picks which one the app starts with — rmp::ui::set_theme() "
           "changes it at runtime.")
    if not isinstance(ui["font"], str):
        raise ConfigError("[ui] font must be a string; \"\" means raylib's built-in font.")
    if not isinstance(ui["font_size"], int) or not (6 <= ui["font_size"] <= 200):
        raise ConfigError(f"[ui] font_size = {ui['font_size']!r} must be an integer between 6 and 200.")
    if not isinstance(ui["scale"], (int, float)) or isinstance(ui["scale"], bool) \
            or ui["scale"] < 0 or ui["scale"] > 8:
        raise ConfigError(f"[ui] scale = {ui['scale']!r} must be a number between 0 and 8 "
                          "(0 = derive it from [window] and the real window size).")
    if not isinstance(ui["max_elements"], int) or not (16 <= ui["max_elements"] <= 65536):
        raise ConfigError(f"[ui] max_elements = {ui['max_elements']!r} must be an integer between "
                          "16 and 65536. It sizes the layout arena, so a large value costs memory "
                          "on every platform including phones.")

    targets = expand_targets(cfg["targets"]["enabled"], cfg["targets"]["disabled"])

    if cfg["raylib"]["disabled_modules"] and "ios" in targets:
        warn("[raylib] disabled_modules has no effect on iOS: it links the prebuilt "
             "raylib.xcframework from the pinned fork, which is built without these flags.")

    # Strict only where being strict costs nobody anything. A Play application id
    # can never be changed once published, so shipping com.example.* is a mistake
    # you cannot walk back — but failing a plain `cmake --preset debug` over it
    # would ruin clone-and-build.
    if strict_release:
        bad = []
        if appid in EXAMPLE_IDS and "android" in targets:
            bad.append(f"[android] application_id is still the example value {appid!r}")
        if bundle in EXAMPLE_IDS and "ios" in targets:
            bad.append(f"[ios] bundle_id is still the example value {bundle!r}")
        if bad:
            raise ConfigError(
                "refusing to build a release with placeholder identifiers:\n  "
                + "\n  ".join(bad)
                + "\n\nA Google Play application id is PERMANENT: once published you can never "
                  "change it.\nSet real values in raylib_multiplatform.toml before tagging.")


# ---------------------------------------------------------------------------
# Version — from the git tag, never from the file
# ---------------------------------------------------------------------------

def resolve_version() -> tuple[str, int]:
    """(versionName, versionCode).

    Read from GITHUB_REF_NAME rather than `git describe`: actions/checkout
    fetches depth 1 with no tags, so git has nothing to describe. Untagged
    builds get 0.0.0-dev / 1.

    versionCode packs the semver into an always-increasing integer. Pre-release
    tags (v1.2.3-rc1) share the code of their base version, which is fine
    because nothing here uploads to Play automatically.
    """
    ref_type = os.environ.get("GITHUB_REF_TYPE", "")
    ref_name = os.environ.get("GITHUB_REF_NAME", "")
    if ref_type == "tag" and ref_name.startswith("v"):
        # Anchored at both ends, and only a -prerelease/+build suffix may follow.
        # Unanchored, 'v1.2.3.4' matched its own prefix: versionName kept the .4
        # while versionCode silently became 1002003, so v1.2.3.4 and v1.2.3.5
        # would collide and Play would reject the second upload for no visible
        # reason.
        # `+` and not `*` on the suffix: semver has no empty pre-release, and
        # `v1.2.3-` would otherwise pass and publish a release literally named
        # "1.2.3-". Found by tests/configure_test.py.
        m = re.fullmatch(r"v(\d+)\.(\d+)\.(\d+)(?:[-+][0-9A-Za-z.\-+]+)?", ref_name)
        if m:
            major, minor, patch = (int(g) for g in m.groups())
            if minor > 999 or patch > 999:
                raise ConfigError(
                    f"tag {ref_name!r}: minor and patch must each stay below 1000 so the Android "
                    "versionCode stays monotonic.")
            return ref_name[1:], major * 1_000_000 + minor * 1_000 + patch
        # ci.yml releases on 'v*', so a v-tag that does not parse is on the
        # release path. Falling back would publish a release named 0.0.0-dev.
        raise ConfigError(
            f"tag {ref_name!r} is not vMAJOR.MINOR.PATCH (optionally -rc1 / +build).\n"
            "Releases take their version from the tag and there is no fallback that "
            "would not be a lie.\nDelete the tag and re-tag: git tag -d "
            f"{ref_name} && git push origin :refs/tags/{ref_name}")
    if ref_type == "tag" and ref_name:
        warn(f"tag {ref_name!r} does not start with 'v'; using 0.0.0-dev.")
    return "0.0.0-dev", 1


