# Android launcher densities. Legacy icons are 48dp, adaptive foregrounds 108dp.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}


def png_size(path: Path) -> tuple[int, int]:
    """Width and height straight out of the IHDR chunk. No dependencies."""
    data = path.read_bytes()[:33]
    if data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise ConfigError(f"[icon] {path.name} is not a PNG.")
    return (int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big"))


def generate_ios_icon(cfg: dict, src: Path) -> None:
    """The iOS app icon, without Pillow.

    Since Xcode 14 a single 1024x1024 image is a complete AppIcon — Xcode
    derives every other size. So this is a file copy, not a resize, which means
    iOS icons work on a macOS runner that has no image library at all. Only
    Android needs real resampling.
    """
    appicon = REPO / "ios" / "Assets.xcassets" / "AppIcon.appiconset"
    w, h = png_size(src)
    if w != h:
        raise ConfigError(f"[icon] {cfg['icon']['source']} is {w}x{h}; it must be square.")
    if w != 1024:
        warn(f"[icon] {cfg['icon']['source']} is {w}x{w}; the App Store requires exactly "
             "1024x1024. Simulator builds will still work.")
    appicon.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, appicon / "icon-1024.png")
    (appicon / "Contents.json").write_text(json.dumps({
        "images": [{"filename": "icon-1024.png", "idiom": "universal",
                    "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "xcode", "version": 1},
    }, indent=2) + "\n")
    (REPO / "ios" / "Assets.xcassets" / "Contents.json").write_text(
        json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")


def generate_icons(cfg: dict, required: bool) -> None:
    src = REPO / cfg["icon"]["source"]
    res = REPO / "raymob" / "app" / "src" / "main" / "res"

    if not src.exists():
        warn(f"[icon] source = {cfg['icon']['source']!r} not found; keeping whatever icons exist.")
        return

    generate_ios_icon(cfg, src)

    # Skip the work when the inputs have not moved. Also the graceful path for a
    # dev machine without Pillow: as long as the icon is unchanged, nobody needs it.
    # Not in res/: that is an Android resource directory with a strict layout,
    # and a stray file there is one AAPT version away from an error.
    marker = REPO / "cmake" / "generated" / "icon.stamp"
    marker.parent.mkdir(parents=True, exist_ok=True)
    want = hashlib.sha256(
        src.read_bytes() + cfg["icon"]["adaptive_background"].encode()).hexdigest()
    if marker.exists() and marker.read_text().strip() == want:
        return

    try:
        from PIL import Image, ImageDraw
    except ImportError:
        # Only Android and iOS consume the generated icons, and those two jobs
        # ask for them explicitly. Everywhere else — the lint job, a macOS or
        # Windows runner, a contributor's laptop — a missing Pillow must not
        # stop the build over an asset that platform will never look at.
        msg = ("[icon] resources/icon.png changed but Pillow is not installed, so the "
               "ANDROID launcher icons cannot be regenerated.\n"
               "  pip install pillow      (or: apt install python3-pil)\n"
               "(iOS is unaffected — its icon is a copy, not a resize.)")
        if required:
            raise ConfigError(msg) from None
        warn(msg + "\n         Skipping — this only matters for Android and iOS builds.")
        return

    source = Image.open(src).convert("RGBA")
    if source.width != source.height:
        raise ConfigError(f"[icon] {cfg['icon']['source']} is {source.width}x{source.height}; "
                          "it must be square.")
    if source.width < 512:
        warn(f"[icon] {cfg['icon']['source']} is only {source.width}px; "
             "1024x1024 is recommended or the largest densities will look soft.")

    def scaled(px: int) -> "Image.Image":
        return source.resize((px, px), Image.LANCZOS)

    def circular(px: int) -> "Image.Image":
        # Supersample the mask so the edge is smooth rather than stair-stepped.
        img = scaled(px)
        mask = Image.new("L", (px * 4, px * 4), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, px * 4 - 1, px * 4 - 1), fill=255)
        img.putalpha(mask.resize((px, px), Image.LANCZOS))
        return img

    def adaptive_foreground(px: int) -> "Image.Image":
        # Android crops adaptive icons to the centre ~66%, so the artwork has to
        # be inset or the launcher will clip it.
        canvas = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        inner = int(px * 0.66)
        canvas.paste(scaled(inner), ((px - inner) // 2, (px - inner) // 2))
        return canvas

    for density, factor in DENSITIES.items():
        d = res / f"mipmap-{density}"
        d.mkdir(parents=True, exist_ok=True)
        scaled(int(48 * factor)).save(d / "ic_launcher.png")
        circular(int(48 * factor)).save(d / "ic_launcher_round.png")
        adaptive_foreground(int(108 * factor)).save(d / "ic_launcher_foreground.png")

    scaled(512).save(REPO / "raymob" / "app" / "src" / "main" / "ic_launcher-playstore.png")

    anydpi = res / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    bg = cfg["icon"]["adaptive_background"]
    background = ("@color/ic_launcher_background" if bg else "@mipmap/ic_launcher_foreground")
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="{background}"/>\n'
                '    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>\n'
                '</adaptive-icon>\n')
    (anydpi / "ic_launcher.xml").write_text(adaptive)
    (anydpi / "ic_launcher_round.xml").write_text(adaptive)

    values = res / "values"
    values.mkdir(parents=True, exist_ok=True)
    (values / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{bg or "#000000"}</color>\n</resources>\n')

    marker.write_text(want + "\n")


def make_default_icon(dest: Path) -> None:
    """Draw the placeholder icon shipped with the template, at [icon] source.

    The destination follows the config rather than being hardcoded to
    branding/icon.png: the folder is the user's to rename, and writing the
    placeholder somewhere the build is not looking would be worse than not
    writing it at all."""
    from PIL import Image, ImageDraw
    size = 1024
    img = Image.new("RGBA", (size, size), (26, 28, 44, 255))
