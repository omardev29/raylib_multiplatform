#!/usr/bin/env python3
"""Turn raylib_multiplatform.toml into everything the build systems need.

The template has four build systems (CMake, Gradle, XcodeGen, GitHub Actions)
and they all need to agree on the same handful of facts: what the game is
called, what its bundle id is, which platforms to build. Left to themselves
they disagree, and the failure is always silent and always expensive — a
release that ships under the wrong identity, or an Android build that quietly
uses a different rres password than the desktop one and cannot read its own
assets.

So there is exactly one hand-written source of truth and one generator. The
build files stay dumb: they read what this wrote, they never parse the config
themselves. Three parsers is three ways to drift.

Nothing this writes is committed — see .gitignore. It is regenerated on every
configure, so it cannot go stale. The price is that Gradle and XcodeGen, which
never invoke CMake, need an explicit `python3 tools/configure.py` step; the CI
workflows have one.

Standard library only. `tomllib` is 3.11+, which the CI image (3.12) and every
supported dev machine have. Pillow is used for icons and is optional — see
generate_icons().

Usage:
    tools/configure.py                     generate everything
    tools/configure.py --check             validate only, write nothing
    tools/configure.py --print-name        the project name
    tools/configure.py --print-targets     JSON array of enabled targets
    tools/configure.py --print-families    JSON array of CI families in play
    tools/configure.py --print-matrix bsd  JSON matrix for one CI family
    tools/configure.py --print-config      the resolved config, as JSON
    tools/configure.py --print-pins        the frozen pins, as key=value
    tools/configure.py --make-default-icon write a placeholder at [icon] source
"""

